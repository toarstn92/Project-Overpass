"""
Safety Responder

Returns a fixed, human-authored safety response for escalated messages.
No LLM call. No exercise. No retrieval.

Design decision: the safety response is NOT generated by a language model.
It is a carefully worded, static response that:
  - Acknowledges the person without minimising
  - Surfaces concrete crisis resources (UK-standard)
  - Hands off to human support
  - Never improvises clinical language

This is the most important path in the system. It is intentionally simple.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Optional

from agent.authored_resources import _CRISIS_RESOURCES, _SAFETY_MESSAGE, _DEFAULT_WATCH_MESSAGE


@dataclass
class SafetyResponse:
    message: str
    path: str = "safety"
    resources: list = None

    def __post_init__(self):
        if self.resources is None:
            self.resources = _CRISIS_RESOURCES


def get_safety_response(
    safety_level: str = "escalate",
    watch_message: Optional[str] = None,
) -> SafetyResponse:
    """
    Return appropriate response based on safety level.

    - escalate: full crisis response, no exercise
    - watch: gentler acknowledgement + soft resource signpost
    """
    if safety_level == "escalate":
        return SafetyResponse(message=_SAFETY_MESSAGE)

    # Watch level: acknowledge + light signpost
    watch_msg = watch_message or _DEFAULT_WATCH_MESSAGE
    return SafetyResponse(
        message=watch_msg,
        path="watch",
        resources=[_CRISIS_RESOURCES[0]],
    )
